int ang,        /* Current scan degree                                  */
    range,
    dir,        /* Heading                                              */
    posx,
    posy        /* Bit variables holding the current position           */
    ;

fire(d,v)
int d,v;
{
    int oang;
	drive(d,v);
	if (range=scan(oang=ang,10)) {
		if (scan(ang-8,5)) {
			if (scan(ang-=5,2)) ;
			else ang-=4;
		} else {
			if (scan(ang+8,5)) {
				if (scan(ang+=5,2)) ;
				else ang+=4;
			} else {
				if (scan(ang,1)) ;
				else if (scan(ang-=3,2)) ; else ang+=6;
			}
		}
		return(cannon((ang<<1)-oang, (scan(ang,10)<<1)-range));
	} else {
		if(range=scan(ang+=20,10)) cannon(ang,range);
		else if(range=scan(ang-=40,10)) cannon(ang,range);
		else if(range=scan(ang+=60,10)) cannon(ang,range);
		else if(range=scan(ang-=80,10)) cannon(ang,range);
		else ang+=120;
	}
}

runX()
{
    dir=180*!posx;
    while( (loc_x()%880) > 120) fire(dir,100);
    fire(dir,0);
}

runY()
{
    dir=270-180*posy;
    while( (loc_y()%880) > 120) fire(dir,100);
    fire(dir,0);
}

main()
{
    int b,deg,i,tmp,flag,timer;
    posy=loc_y(posx=loc_x()>499)>499;
    deg=90*((posy<<1)|(posx^posy));
    while (1)
    {
        if (flag^posx^posy) runY(runX()); else runX(runY());
        while((timer<2) && (i < 140)) { timer+=(scan(deg+i,10)>0); i+=20; }
        while(timer<2)
        {
            if (((posx=loc_x())%880)<120) dir=180*(posx>500);
            else if (((posy=loc_y())%880)<120) dir=90+180*(posy>500);
            else if (range>610) dir=ang+15+330*(b^=1);
            else if (range<180) dir=ang+180;
            else dir=ang+180*(b^=1);

            fire(dir,100);
            fire(dir,100);
            fire(dir,100);
        }
        dir=(deg+(30<<flag));
        if (scan(tmp=deg+90*flag,10)) ang=tmp;
        timer=9 - (damage()/25);
        while(--timer) fire(dir,100);
        i=0; flag^=1;
    }
}
