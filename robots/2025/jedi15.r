int
    ang,range,d,dir,posx,posy,flag,timer,
    enemies,t,b,deg1,deg2,fp,skip;

stop()
{
  qfire(dir,skip=t=0);
  /*while(speed()>59) ;*/
}

fastradar() /* Count enemies */
{
  return enemies=3
  -(scan(deg1+100,10)!=0)
  -(scan(deg1+80, 10)!=0)
  -(scan(deg1+60, 10)!=0)
  -(scan(deg1+40, 10)!=0)
  -(scan(deg1+20, 10)!=0)
  -(scan(deg1,    10)!=0)
  ;
}

runX()
{
  dir=180*!posx;
  if(posx) { xmin(); }
  else     { xmax(); }
}

runY()
{
  dir=270-180*posy;
  if(posy) { ymin(); }
  else     { ymax(); }
}

corner()
{
    stop(); if (flag^posx^posy) runY(runX()); else runX(runY());
}

xmax() { while(loc_x()>88) qfire(dir,100);   while(loc_x()>50) drive(dir,100);   stop(); }
xmin() { while(loc_x()<912) qfire(dir,100);  while(loc_x()<950) drive(dir,100);  stop(); }
ymax() { while(loc_y()>88) qfire(dir,100);   while(loc_y()>50) drive(dir,100);   stop(); }
ymin() { while(loc_y()<912) qfire(dir,100);  while(loc_y()<950) drive(dir,100);  stop(); }

move() {
    if (range>710) {
        ang=deg1;
    }
    qfire(dir,100);
    if (damage()<60) fire();
    qfire(dir,100);
    qfire(dir+=180,0);
}

fire() 
{
  int orange,oang;
  drive(dir,100);
  if (scan(ang,10));
  else if (scan(ang-=21,10));
  else if (scan(ang+=42,10));
  else if (scan(ang+=21,10));
  else return search();

  if (scan(ang-17,10)) ang-=6;  
  if (scan(ang+17,10)) ang+=6;


  
  if (orange=refine()) {
    if (range=refine(oang=ang))
      cannon(ang+(ang-oang)*((1200+range)>>9)-(sin(ang-dir)>>14),
                    range*192/(192+orange-range-(cos(ang-dir)>>12)));
    else if(range=scan(ang-=21,10)) cannon(ang,range); 
    else if(range=scan(ang+=42,10)) cannon(ang,range);
    else ang+=41;
  }
  else if(orange=scan(ang-=21,10)) cannon(ang,orange); 
  else if(orange=scan(ang+=42,10)) cannon(ang,orange);
  else ang+=41;
}

refine() {
  if (scan(ang+13,10)) ang+=4; if (scan(ang-13,10)) ang-=4;
  if (scan(ang+12,10)) ang+=2; if (scan(ang-12,10)) ang-=2;
  if (scan(ang+10,10)) ++ang; if (scan(ang-10,10)) --ang;
  return scan(ang,10);

}

search() {
  if ((range=scan(ang-=84,10))) return cannon(ang,range);
  else if ((range=scan(ang-=21,10))) return cannon(ang,range);
  else if ((range=scan(ang+=126,10))) return cannon(ang,range);
  else if ((range=scan(ang+=21,10))) return cannon(ang,range);
  else if ((range=scan(ang-=168,10))) return cannon(ang,range);
  else if ((range=scan(ang-=21,10))) return cannon(ang,range);
  else if ((range=scan(ang+=210,10))) return cannon(ang,range);
  else if ((range=scan(ang-=231,10))) return cannon(ang,range);
  else if ((range=scan(ang+=252,10))) return cannon(ang,range);
  else ang+=41;
}

qfire(d,v)
int d,v;
{
    int orange;
    drive(d,v);
    if ((orange=scan(ang, 10)) ) { 
            if (scan(ang-9,4)) { 
                    if (scan(ang-=13,4)) { 
                            if(scan(ang-6,fp)) ang-=6;
                    }  else if (scan(ang-fp,fp)) --ang;
            } else if(scan(ang+9,fp)) { 
                    if (scan(ang+=13,fp)) ang+=fp;
            }  else if(scan(ang+4,fp)) ang+=fp;
            else ang-=2;
    }  else if ((orange=scan(ang-=21,10))) { 
            if (scan(ang-9,10)) { 
                    if (scan(ang-=13,fp)) ang-=fp;
            } else if(scan(ang+9,10)) ang+=6; 
    }  else if ((orange=scan(ang+=42,10))) { 
            if (scan(ang+9,10)) ang+=12;
    }  else if ((orange=scan(ang+=21,10)));
        else if(skip) return search();
        else {
                    if ((orange=scan(ang+=21,10))) return cannon(ang,range=orange); 
            range=0;
                    return ang+=41; 
        } 
            if (range=scan(ang,10)){  
                    cannon (ang, range*145/(145+orange-range) );
            }  else if(range=scan(ang-=21,10)) cannon(ang,range); 
            else if(range=scan(ang+=42,10)) cannon(ang,range);
        else ang+=41;
}

int look(a)
int a;
{
       if (range=scan(a,10))    ;
  else if (range=scan(a+=20,10));
  else return 0;
  ang=a;
  return range>820;
}

slowradar(s)
int s;
{
  int deg,brange;
  if (s) return;
  deg=deg1-20; brange=1500; enemies=3;
  while( (deg<=deg2) && enemies)
  if (range=scan(deg+=20, 10))
  {
      --enemies;
      if (range<brange)
      {
          ang=deg;
          brange=range;
      }
  }
}


main()
{
    int heading,xy,safe,dam;
    posx=loc_x(posy=(loc_y(fp=3)>500))>500;
    skip=( fastradar(corner(deg2=(deg1=(90*(heading=(posy<<1)|(posx^posy))))+100)) < 1);
    while (1) {
      if (enemies>1) {
        skip=fp=5;
        fire(qfire(dir=deg1+40,100)); 
        while(1) /* F2F inspired by loneliness and carillon */
        {
            if(range>459) fire();
            if (((posx=loc_x(posy=loc_y()))%840)<160) dir=20+320*(posy>=500)+180*(posx>=500);
            else if ((posy%840)<160)  dir=70+40*(posx>=500)+180*(posy>=500);
            else if (range<149) dir=((ang/90)+(b^=1))*90+180*(dam>85);
            else if (range<640) dir=ang+80+(b^=1)*200+180*(dam>79);
            else                dir=ang+24+(b^=1)*(299-dam);
            dam=damage(qfire(dir,100));
            if(scan(ang-15,10)) ang-=4;
            if(scan(ang+15,10)) ang+=4;
            qfire(dir,100);
        }
      }
      while(enemies==1) /* 3vs3 */
      {
          if (look(deg1))
          {
              dir=deg1+(30<<flag);
              if (look(deg1+(70*flag)))
              {
                  fire();
                  while(scan(ang,10)>680) fire();
                  corner();
                  flag^=1;
              }
              else if (scan(dir,10))
              {
                  ang=dir;
                  fire();
                  while(scan(ang,10)>640) fire();
                  corner();
                  flag^=1;
              }
              else
              {
                  while(++t<4) fire();
                  corner();
                  if (damage()>d)
                  {
                      flag^=1;
                  }
                  d=damage()+4;
              }
              if ((++timer%2)&&(range>400))
              {
                  if ((timer>64)&&(damage()<40)) enemies=2;
                  else slowradar(skip);
              }
          }
          else
          {
              dir=deg1;
              while(t<4)
              {
                  if (heading&1) xy=loc_y();  else xy=loc_x();
                  if (heading&2) safe=xy>180; else safe=xy<820;

                  if (safe) fire();
                  else
                  {
                      qfire(dir+=90,0); if (scan(dir,10)) ang=dir; ++heading; timer+=++t;
                  }
              }
              fastradar(t=0);
          }
      }
      while (enemies<1) /* 4vs4 */
      {
          if (scan(deg1,10)||scan(deg1+90,10)) {
              if (posy) {
                  ymin(move(dir=300-60*(posx)));
              }
              else {
                  ymax(move(dir=60+60*(posx)));
              }

              if (posx) {
                  xmin(move(dir=150+60*(posy)));
              }
              else {
                  xmax(move(dir=30-60*(posy)));
              }
          } else {
              if (posy) {
                  ymin(move(dir=270));
              } else {
                  ymax(move(dir=90));
              }

              if (posx) {
                  xmin(move(dir=180));
              }
              else {
                  xmax(move(dir=0));
              }
          }

          if ((++timer%4 == 1)&&(range>400))
          {
              if ((timer>32)&&(damage()<40)) enemies=1;
              else slowradar(0);
          }
      }
    }
}

