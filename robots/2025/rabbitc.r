int ang,range,dir;

fire() 
{
  int orange,oang;
  drive(dir,100);
  if (scan(ang,10));
  else if (scan(ang-=21,10));
  else if (scan(ang+=42,10));
  else if (scan(ang+=21,10));
  else return search();

  if (scan(ang-17,10)) ang-=6;  
  if (scan(ang+17,10)) ang+=6;


  
  if (orange=refine()) {
    if (range=refine(oang=ang))
      cannon(ang+(ang-oang)*((1200+range)>>9)-(sin(ang-dir)>>14),
                    range*192/(192+orange-range-(cos(ang-dir)>>12)));
    else if(range=scan(ang-=21,10)) cannon(ang,range); 
    else if(range=scan(ang+=42,10)) cannon(ang,range);
    else ang+=41;
  }
  else if(orange=scan(ang-=21,10)) cannon(ang,orange); 
  else if(orange=scan(ang+=42,10)) cannon(ang,orange);
  else ang+=41;
}

refine() {
  if (scan(ang+13,10)) ang+=4; if (scan(ang-13,10)) ang-=4;
  if (scan(ang+12,10)) ang+=2; if (scan(ang-12,10)) ang-=2;
  if (scan(ang+10,10)) ++ang; if (scan(ang-10,10)) --ang;
  return scan(ang,10);

}

search() {
  if ((range=scan(ang-=84,10))) return cannon(ang,range);
  else if ((range=scan(ang-=21,10))) return cannon(ang,range);
  else if ((range=scan(ang+=126,10))) return cannon(ang,range);
  else if ((range=scan(ang+=21,10))) return cannon(ang,range);
  else if ((range=scan(ang-=168,10))) return cannon(ang,range);
  else if ((range=scan(ang-=21,10))) return cannon(ang,range);
  else if ((range=scan(ang+=210,10))) return cannon(ang,range);
  else if ((range=scan(ang-=231,10))) return cannon(ang,range);
  else if ((range=scan(ang+=252,10))) return cannon(ang,range);
  else ang+=41;
}

